function replaceQuestionMarks(sql, params) {
  let output = '';
  const values = [];

  for (let index = 0; index < sql.length; index += 1) {
    const char = sql[index];

    if (char !== '?') {
      output += char;
      continue;
    }

    const parameter = params.shift();

    if (Array.isArray(parameter)) {
      const placeholders = parameter.map((_, position) => `$${values.length + position + 1}`).join(', ');
      output += `(${placeholders})`;
      values.push(...parameter);
      continue;
    }

    output += `$${values.length + 1}`;
    values.push(parameter);
  }

  return {
    sql: output,
    values,
  };
}

function normalizeQuery(sql, params = []) {
  const transformed = replaceQuestionMarks(sql, [...params]);
  let normalizedSql = transformed.sql
    .replace(/CURDATE\(\)/gi, 'CURRENT_DATE')
    .replace(/\bNOW\(\)/gi, 'CURRENT_TIMESTAMP')
    .replace(/\bis_active\s*=\s*1\b/gi, 'is_active = TRUE')
    .replace(/\bis_active\s*=\s*0\b/gi, 'is_active = FALSE');

  if (/^\s*INSERT\b/i.test(normalizedSql) && !/\bRETURNING\b/i.test(normalizedSql)) {
    normalizedSql += ' RETURNING id';
  }

  return {
    text: normalizedSql,
    values: transformed.values,
  };
}

function serializeResult(result, sql) {
  if (/^\s*SELECT/i.test(sql)) {
    return [result.rows];
  }

  const insertId = result.rows?.[0]?.id ?? undefined;
  return [{ insertId, rowCount: result.rowCount }];
}

function createPgAdapter() {
  const pool = new pg.Pool({
    connectionString: supabaseConnectionString,
    max: Number(process.env.DB_CONNECTION_LIMIT || 10),
    ssl: process.env.SUPABASE_SSL === 'true' ? { rejectUnauthorized: false } : undefined,
    family: 4,
    connectTimeoutMillis: Number(process.env.DB_CONNECT_TIMEOUT_MS || 10000),
    idleTimeoutMillis: Number(process.env.DB_IDLE_TIMEOUT_MS || 30000),
  });

  pool.on('error', (error) => {
    console.error('Supabase Postgres pool error:', error);
  });

  return {
    async query(sql, params = []) {
      const { text, values } = normalizeQuery(sql, params);
      const result = await pool.query(text, values);
      return serializeResult(result, sql);
    },
    async getConnection() {
      const client = await pool.connect();

      return {
        async query(sql, params = []) {
          const { text, values } = normalizeQuery(sql, params);
          const result = await client.query(text, values);
          return serializeResult(result, sql);
        },
        async beginTransaction() {
          await client.query('BEGIN');
        },
        async commit() {
          await client.query('COMMIT');
        },
        async rollback() {
          await client.query('ROLLBACK');
        },
        release() {
          client.release();
        },
      };
    },
  };
}

function createMysqlAdapter() {
  const pool = mysql.createPool(mysqlConfig);

  pool.on('error', (error) => {
    console.error('MySQL pool error:', error);
  });

  return pool;
}

const pool = provider === 'supabase' ? createPgAdapter() : createMysqlAdapter();

export async function testConnection() {
  if (provider === 'supabase') {
    const result = await pool.query('SELECT 1 AS ok');
    return Array.isArray(result[0]) && result[0].length > 0;
  }

  const connection = await pool.getConnection();

  try {
    const [rows] = await connection.query('SELECT 1 AS ok');
    return Array.isArray(rows) && rows.length > 0;
  } finally {
    connection.release();
  }
}

async function ensureCompatibilitySchema() {
  if (provider !== 'supabase') {
    return;
  }

  for (const statement of compatibilitySchemaStatements) {
    await pool.query(statement);
  }

  await pool.query(`
    CREATE OR REPLACE FUNCTION public.touch_updated_at()
    RETURNS TRIGGER AS $$
    BEGIN
      NEW.updated_at = NOW();
      RETURN NEW;
    END;
    $$ LANGUAGE plpgsql;
  `);

  await pool.query(`
    DO $$
    BEGIN
      IF NOT EXISTS (
        SELECT 1 
        FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name = 'shops' 
          AND column_name = 'store_size'
      ) THEN
        ALTER TABLE public.shops ADD COLUMN store_size INT DEFAULT 0;
      END IF;
    END $$;
  `);

  const triggerTargets = ['admins', 'employees', 'shops', 'products', 'complaints'];

  for (const tableName of triggerTargets) {
    await pool.query(`
      DO $$
      BEGIN
        IF NOT EXISTS (
          SELECT 1
          FROM pg_trigger
          WHERE tgname = '${tableName}_updated_at'
        ) THEN
          CREATE TRIGGER ${tableName}_updated_at
          BEFORE UPDATE ON public.${tableName}
          FOR EACH ROW
          EXECUTE FUNCTION public.touch_updated_at();
        END IF;
      END $$;
    `);
  }

  await pool.query(`
    DO $$
    BEGIN
      IF NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints
        WHERE constraint_name = 'bills_shop_fk'
          AND table_schema = 'public'
          AND table_name = 'bills'
      ) THEN
        ALTER TABLE public.bills
          ADD CONSTRAINT bills_shop_fk
          FOREIGN KEY (shop_id) REFERENCES public.shops(id) ON DELETE SET NULL;
      END IF;

      IF NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints
        WHERE constraint_name = 'bill_items_bill_fk'
          AND table_schema = 'public'
          AND table_name = 'bill_items'
      ) THEN
        ALTER TABLE public.bill_items
          ADD CONSTRAINT bill_items_bill_fk
          FOREIGN KEY (bill_id) REFERENCES public.bills(id) ON DELETE CASCADE;
      END IF;

      IF NOT EXISTS (
        SELECT 1
        FROM information_schema.table_constraints
        WHERE constraint_name = 'complaints_shop_fk'
          AND table_schema = 'public'
          AND table_name = 'complaints'
      ) THEN
        ALTER TABLE public.complaints
          ADD CONSTRAINT complaints_shop_fk
          FOREIGN KEY (shop_id) REFERENCES public.shops(id) ON DELETE SET NULL;
      END IF;
    END $$;
  `);
}

export async function ensureForeignKeys() {
  await ensureCompatibilitySchema();
}

